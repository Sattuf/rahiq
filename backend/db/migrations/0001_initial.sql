  PRIMARY KEY (product_id, code)
);

CREATE TABLE catalog.media (
  id uuid PRIMARY KEY,
  product_id uuid NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('catalog','detail','scale','packaging','mood')),
  storage_key text NOT NULL,
  content_type text NOT NULL,
  width int NOT NULL,
  height int NOT NULL,
  -- Law 8: generated or placeholder imagery is flagged and never shown as the product photo.
  is_generated boolean NOT NULL DEFAULT false,
  alt jsonb NOT NULL DEFAULT '{}',
  sort_order int NOT NULL DEFAULT 0,
  CHECK (NOT (is_generated AND role <> 'mood'))
);
CREATE INDEX ix_media_product ON catalog.media (product_id, sort_order);

CREATE TABLE catalog.notes (
