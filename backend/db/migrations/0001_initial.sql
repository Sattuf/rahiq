  status text NOT NULL CHECK (status IN ('pending','succeeded','failed')),
  provider_ref text,
  requested_by uuid,
  approved_by uuid,
  failure_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
