  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_order_history_order ON ordering.order_status_history (order_id, at);
CREATE TRIGGER order_history_append_only BEFORE UPDATE OR DELETE ON ordering.order_status_history
  FOR EACH ROW EXECUTE FUNCTION infra.forbid_change();

CREATE TABLE ordering.order_notes (
  id uuid PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES ordering.orders(id),
