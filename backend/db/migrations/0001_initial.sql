-- ───────────────────────────── inventory ─────────────────────────────
CREATE TABLE inventory.batches (
  id uuid PRIMARY KEY,
  variant_id uuid NOT NULL,
  code text NOT NULL,
  qty_received int NOT NULL CHECK (qty_received > 0),
  qty_on_hand int NOT NULL CHECK (qty_on_hand >= 0),
  qty_reserved int NOT NULL DEFAULT 0 CHECK (qty_reserved >= 0),
  produced_at date,
  best_before date,
  origin jsonb,
  lab_report_key text,
  lab_summary jsonb,
  public_token text UNIQUE,
  received_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (variant_id, code),
  -- The last line of defence against overselling: even buggy code cannot reserve what is not there.
  CHECK (qty_reserved <= qty_on_hand),
  CHECK (best_before IS NULL OR produced_at IS NULL OR best_before > produced_at)
);
CREATE INDEX ix_batches_fefo ON inventory.batches (variant_id, best_before NULLS LAST)
  WHERE qty_on_hand > qty_reserved;

CREATE TABLE inventory.reservations (
  id uuid PRIMARY KEY,
  checkout_id uuid NOT NULL,
  order_id uuid,
  batch_id uuid NOT NULL REFERENCES inventory.batches(id),
  variant_id uuid NOT NULL,
  qty int NOT NULL CHECK (qty > 0),
  status text NOT NULL CHECK (status IN ('held','committed','released')),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz
);
CREATE INDEX ix_reservations_expiry ON inventory.reservations (expires_at) WHERE status = 'held';
CREATE INDEX ix_reservations_order ON inventory.reservations (order_id);

CREATE TABLE inventory.movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id uuid NOT NULL REFERENCES inventory.batches(id),
  delta int NOT NULL CHECK (delta <> 0),
  reason text NOT NULL CHECK (reason IN ('received','sold','returned','damaged','adjustment')),
  note text,
  ref_id uuid,
  actor_id uuid,
  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_movements_batch ON inventory.movements (batch_id, at);
CREATE TRIGGER movements_append_only BEFORE UPDATE OR DELETE ON inventory.movements
  FOR EACH ROW EXECUTE FUNCTION infra.forbid_change();

CREATE TABLE inventory.stock_settings (
  variant_id uuid PRIMARY KEY,
  low_stock_threshold int NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
  requires_expiry boolean NOT NULL DEFAULT false,
  low_stock_alerted_at timestamptz
);

-- ───────────────────────────── pricing ─────────────────────────────
CREATE TABLE pricing.prices (
  variant_id uuid NOT NULL,
  currency char(3) NOT NULL,
  amount bigint NOT NULL CHECK (amount >= 0),
  valid_from timestamptz NOT NULL,
  valid_to timestamptz,
  set_by uuid,
  PRIMARY KEY (variant_id, currency, valid_from),
  CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE UNIQUE INDEX ux_prices_open ON pricing.prices (variant_id, currency) WHERE valid_to IS NULL;

CREATE TABLE pricing.tax_rates (
  category text NOT NULL,
  rate_bp int NOT NULL CHECK (rate_bp BETWEEN 0 AND 10000),
  valid_from date NOT NULL,
  PRIMARY KEY (category, valid_from)
);

CREATE TABLE pricing.coupons (
  id uuid PRIMARY KEY,
  code citext UNIQUE NOT NULL,
  kind text NOT NULL CHECK (kind IN ('percent','fixed','free_shipping')),
  value bigint NOT NULL CHECK (value >= 0),
  currency char(3) NOT NULL DEFAULT 'TRY',
  min_subtotal bigint CHECK (min_subtotal >= 0),
  section text CHECK (section IN ('perfume','honey','shared')),
  max_uses int CHECK (max_uses > 0),
  used_count int NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  per_customer_limit int CHECK (per_customer_limit > 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean NOT NULL DEFAULT true,
  description text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (max_uses IS NULL OR used_count <= max_uses),
  CHECK (kind <> 'percent' OR value BETWEEN 1 AND 10000)
);

CREATE TABLE pricing.coupon_redemptions (
  id uuid PRIMARY KEY,
  coupon_id uuid NOT NULL REFERENCES pricing.coupons(id),
  order_id uuid NOT NULL UNIQUE,
  customer_key text NOT NULL,
  status text NOT NULL CHECK (status IN ('held','committed','released')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_redemptions_customer ON pricing.coupon_redemptions (coupon_id, customer_key) WHERE status <> 'released';

