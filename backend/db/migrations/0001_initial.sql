CREATE TABLE ordering.return_requests (
  id uuid PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES ordering.orders(id),
  status text NOT NULL CHECK (status IN ('requested','approved','rejected','received','refunded')),
  kind text NOT NULL CHECK (kind IN ('withdrawal','damaged','wrong_item')),
  reason text NOT NULL,
  lines jsonb NOT NULL,
  photo_keys text[] NOT NULL DEFAULT '{}',
  resolution_note text,
  refund_amount bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (kind = 'withdrawal' OR cardinality(photo_keys) > 0)
);
CREATE INDEX ix_returns_order ON ordering.return_requests (order_id);

-- ───────────────────────────── payments ─────────────────────────────
CREATE TABLE payments.payments (
  id uuid PRIMARY KEY,
  order_id uuid NOT NULL,
  order_number text NOT NULL,
  provider text NOT NULL,
  provider_ref text,
  session_token text,
  method text NOT NULL CHECK (method IN ('card','cod')),
  amount bigint NOT NULL CHECK (amount >= 0),
  refunded_amount bigint NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
  currency char(3) NOT NULL,
  installments int NOT NULL DEFAULT 1 CHECK (installments >= 1),
  status text NOT NULL CHECK (status IN ('pending','succeeded','failed','refunded','partially_refunded','collected_on_delivery')),
  failure_reason text,
  raw_last_event jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (refunded_amount <= amount)
);
CREATE INDEX ix_payments_order ON payments.payments (order_id);
CREATE INDEX ix_payments_pending ON payments.payments (created_at) WHERE status = 'pending';
CREATE UNIQUE INDEX ux_payments_provider_ref ON payments.payments (provider, provider_ref) WHERE provider_ref IS NOT NULL;

