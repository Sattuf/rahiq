-- Rows in append-only tables can never be changed or removed, even by a bug (security.md §6, data-model.md §7).
CREATE OR REPLACE FUNCTION infra.forbid_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'table %.% is append-only', TG_TABLE_SCHEMA, TG_TABLE_NAME;
END $$;

