-- ───────────────────────────── ordering ─────────────────────────────
CREATE SEQUENCE ordering.order_number_seq START 1;

CREATE TABLE ordering.checkouts (
  id uuid PRIMARY KEY,
  cart_id uuid NOT NULL,
  customer_id uuid,
  email citext,
  phone text,
  shipping_address jsonb,
  billing_address jsonb,
  is_gift boolean NOT NULL DEFAULT false,
  gift_message text CHECK (length(gift_message) <= 300),
  hide_prices boolean NOT NULL DEFAULT false,
  shipping_method text,
  coupon_code text,
  locale text NOT NULL,
  marketing_consent boolean NOT NULL DEFAULT false,
  status text NOT NULL CHECK (status IN ('open','completed','abandoned')),
  order_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ordering.orders (
  id uuid PRIMARY KEY,
  number text NOT NULL UNIQUE,
  checkout_id uuid NOT NULL UNIQUE,
  customer_id uuid,
  email citext NOT NULL,
  phone text,
  status text NOT NULL CHECK (status IN ('pending_payment','confirmed','preparing','shipped','delivered','returned_to_sender','return_requested','returned','refunded','cancelled')),
  payment_method text NOT NULL CHECK (payment_method IN ('card','cod')),
  currency char(3) NOT NULL,
  subtotal bigint NOT NULL CHECK (subtotal >= 0),
  discount bigint NOT NULL CHECK (discount >= 0),
  shipping bigint NOT NULL CHECK (shipping >= 0),
  cod_fee bigint NOT NULL DEFAULT 0 CHECK (cod_fee >= 0),
  tax bigint NOT NULL CHECK (tax >= 0),
  total bigint NOT NULL CHECK (total >= 0),
  shipping_method text NOT NULL,
  shipping_address jsonb NOT NULL,
  billing_address jsonb NOT NULL,
  is_gift boolean NOT NULL DEFAULT false,
  gift_message text,
  hide_prices boolean NOT NULL DEFAULT false,
  coupon_code text,
  locale text NOT NULL,
  contract_doc_hash text NOT NULL,
  fraud_flags text[] NOT NULL DEFAULT '{}',
  placed_at timestamptz NOT NULL,
  reservation_expires_at timestamptz,
  idempotency_key text UNIQUE,
  -- Prices are tax-inclusive; tax is informational and already inside the lines (ADR-017).
  CHECK (total = subtotal - discount + shipping + cod_fee),
  CHECK (discount <= subtotal)
);
CREATE INDEX ix_orders_customer ON ordering.orders (customer_id, placed_at DESC);
CREATE INDEX ix_orders_status ON ordering.orders (status, placed_at);
CREATE INDEX ix_orders_email ON ordering.orders (email);

CREATE TABLE ordering.order_lines (
  id uuid PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES ordering.orders(id),
  variant_id uuid NOT NULL,
  product_id uuid NOT NULL,
  sku text NOT NULL,
  section text NOT NULL,
  product_type text NOT NULL,
  name_snapshot text NOT NULL,
  variant_label_snapshot text NOT NULL,
  warnings_snapshot text[] NOT NULL,
  is_sample boolean NOT NULL DEFAULT false,
  shipping_class text NOT NULL,
  group_id uuid,
  group_label_snapshot text,
  unit_price bigint NOT NULL CHECK (unit_price >= 0),
  qty int NOT NULL CHECK (qty > 0),
  discount bigint NOT NULL DEFAULT 0 CHECK (discount >= 0),
  tax_rate_bp int NOT NULL,
  tax_amount bigint NOT NULL CHECK (tax_amount >= 0),
  line_total bigint NOT NULL CHECK (line_total >= 0),
  batch_allocations jsonb,
  returnable boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  CHECK (line_total = unit_price * qty - discount)
);
CREATE INDEX ix_order_lines_order ON ordering.order_lines (order_id);
CREATE INDEX ix_order_lines_batches ON ordering.order_lines USING gin (batch_allocations jsonb_path_ops);

CREATE TABLE ordering.order_status_history (
