-- Old slugs keep working with a 301 (content-seo.md §3).
CREATE TABLE catalog.slug_redirects (
  old_slug text PRIMARY KEY,
  product_id uuid NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE
);

CREATE TABLE catalog.variants (
  id uuid PRIMARY KEY,
  product_id uuid NOT NULL REFERENCES catalog.products(id),
  sku text NOT NULL UNIQUE,
  volume_ml int CHECK (volume_ml > 0),
  weight_g int CHECK (weight_g > 0),
  gtin text,
  shipping_weight_g int NOT NULL CHECK (shipping_weight_g > 0),
  shipping_class text NOT NULL CHECK (shipping_class IN ('standard','fragile','liquid','flammable')),
  is_sample boolean NOT NULL DEFAULT false,
  -- 'batches': own stock. 'components': a bundle whose stock is its parts (product-domain.md §4.3).
  stock_mode text NOT NULL DEFAULT 'batches' CHECK (stock_mode IN ('batches','components')),
  is_active boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  CHECK (volume_ml IS NOT NULL OR weight_g IS NOT NULL OR stock_mode = 'components')
);
CREATE INDEX ix_variants_product ON catalog.variants (product_id);

-- Fixed bundles: which variants a bundle variant contains.
